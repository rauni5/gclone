package guide

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/rauni5/gclone/internal/adapters"
	"github.com/rauni5/gclone/internal/buildinfo"
	"github.com/rauni5/gclone/internal/project"
	"github.com/rauni5/gclone/internal/repos"
	"github.com/rauni5/gclone/internal/services"
	"github.com/rauni5/gclone/internal/verify"
)

func WriteGuide(p *project.Project) (string, error) {
	var b strings.Builder
	w := func(format string, a ...interface{}) { fmt.Fprintf(&b, format+"\n", a...) }

	w("# Setup guide: %s", filepath.Base(p.Dir))
	w("")
	w("_Generated by gclone %s on %s from `%s` (commit `%s`)._", buildinfo.Version, time.Now().Format("2006-01-02 15:04"), p.URL, p.Commit)
	w("")

	// What was done
	w("## What gclone did")
	w("")
	if len(p.Steps) == 0 {
		w("Nothing was run (everything was already in place or skipped).")
	} else {
		w("| Step | Where | Result |")
		w("|---|---|---|")
		for _, s := range p.Steps {
			res := s.Status
			if s.Note != "" {
				res += ": " + strings.ReplaceAll(s.Note, "|", "/")
			}
			w("| %s (`%s`) | %s | %s |", s.Name, s.Cmd, s.Where, res)
		}
		var failed []project.Step
		for _, s := range p.Steps {
			if s.Hint != "" {
				failed = append(failed, s)
			}
		}
		if len(failed) > 0 {
			w("")
			w("**What probably went wrong** (a best guess from the error output, check the terminal log):")
			w("")
			for _, s := range failed {
				w("- %s: %s", s.Name, s.Hint)
			}
		}
	}
	w("")

	// Warnings
	var warns []string
	warns = append(warns, p.Warnings...)
	for _, a := range adapters.All() {
		warns = append(warns, a.Warnings(p)...)
	}
	if len(warns) > 0 {
		w("## Warnings")
		w("")
		for _, x := range warns {
			w("- %s", x)
		}
		w("")
	}

	// Run it
	w("## Run it")
	w("")
	units := 0
	for _, a := range adapters.All() {
		units += a.Units(p)
	}
	if units > 1 {
		w("This repo has %d projects. Run each one in its own terminal.", units)
		w("")
	}
	for _, c := range p.Composes {
		if len(c.DBServices) == 0 {
			continue
		}
		state := "not started by gclone"
		if c.Started {
			state = "started by gclone"
		}
		w("**Local services** (`%s`, %s): %s", c.Rel, strings.Join(c.DBServices, ", "), state)
		w("")
		w("```bash")
		w("docker compose -f %s up -d %s", c.Rel, strings.Join(c.DBServices, " "))
		w("```")
		w("")
	}
	for _, a := range adapters.All() {
		b.WriteString(a.Guide(p))
	}

	// Config changes
	w("## What you may need to change")
	w("")
	any := false
	for _, a := range adapters.All() {
		for _, sec := range a.GuideConfig(p) {
			b.WriteString(sec)
			any = true
		}
	}
	if !any {
		w("No env files or environment variables were detected. The project should run on its defaults.")
		w("")
	}

	services.GuideServices(&b, p)
	repos.GuideCompanions(&b, p)

	// Databases
	var dbLines []string
	for _, pkg := range p.Pkgs {
		if len(pkg.DBHints) > 0 {
			dbLines = append(dbLines, fmt.Sprintf("- `%s` uses: %s", pkg.Rel, strings.Join(pkg.DBHints, ", ")))
		}
	}
	if len(dbLines) > 0 {
		w("## Databases")
		w("")
		for _, l := range dbLines {
			w("%s", l)
		}
		w("")
		w("Make sure the database is reachable with the connection settings in your `.env` before starting the app.")
		for _, pkg := range p.Pkgs {
			if pkg.Prisma {
				w("")
				w("Prisma detected in `%s`: run `npx prisma generate`, then `npx prisma migrate dev` once the database is up.", pkg.Rel)
			}
		}
		w("")
	}

	if len(p.OtherStacks) > 0 {
		w("## Not handled by gclone yet")
		w("")
		for _, s := range p.OtherStacks {
			w("- %s", s)
		}
		w("")
		w("These parts were cloned but not set up. Check the repository README for their steps.")
		w("")
	}

	if p.Verify != nil {
		b.WriteString(verify.VerifySection(p.Verify))
	}

	w("---")
	w("Keep `.env` files out of version control. This guide is excluded from `git status` through `.git/info/exclude`.")

	path := filepath.Join(p.Dir, project.GuideName)
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return "", err
	}
	excludeFromGit(p.Dir, project.GuideName)
	return path, nil
}

// excludeFromGit keeps the generated guide out of `git status`.
func excludeFromGit(dir, name string) {
	info := filepath.Join(dir, ".git", "info")
	if err := os.MkdirAll(info, 0o755); err != nil {
		return
	}
	path := filepath.Join(info, "exclude")
	b, _ := os.ReadFile(path)
	if strings.Contains(string(b), name) {
		return
	}
	f, err := os.OpenFile(path, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
	if err != nil {
		return
	}
	defer f.Close()
	if len(b) > 0 && !strings.HasSuffix(string(b), "\n") {
		_, _ = f.WriteString("\n")
	}
	_, _ = f.WriteString(name + "\n")
}
