func WriteGuide(p *project.Project) (string, error) {
	var b strings.Builder
	w := func(format string, a ...interface{}) { fmt.Fprintf(&b, format+"\n", a...) }

	w("# Setup guide: %s", filepath.Base(p.Dir))
	w("")
	w("_Generated by gclone %s on %s from `%s` (commit `%s`)._", buildinfo.Version, time.Now().Format("2006-01-02 15:04"), p.URL, p.Commit)
	w("")

	// What was done
	w("## What gclone did")
	w("")
	if len(p.Steps) == 0 {
		w("Nothing was run (everything was already in place or skipped).")
	} else {
		w("| Step | Where | Result |")
		w("|---|---|---|")
		for _, s := range p.Steps {
			res := s.Status
			if s.Note != "" {
				res += ": " + strings.ReplaceAll(s.Note, "|", "/")
			}
			w("| %s (`%s`) | %s | %s |", s.Name, s.Cmd, s.Where, res)
		}
	}
	w("")

	// Warnings
	var warns []string
	warns = append(warns, p.Warnings...)
	for _, pkg := range p.Pkgs {
		for _, x := range pkg.Warnings {
			warns = append(warns, pkg.Rel+": "+x)
		}
	}
	if len(warns) > 0 {
		w("## Warnings")
		w("")
		for _, x := range warns {
			w("- %s", x)
		}
		w("")
	}

	// Run it
	w("## Run it")
	w("")
	if len(p.Pkgs) > 1 {
		w("This repo has %d packages. Run each one in its own terminal.", len(p.Pkgs))
		w("")
	}
	for _, c := range p.Composes {
		if len(c.DBServices) == 0 {
			continue
		}
		state := "not started by gclone"
		if c.Started {
			state = "started by gclone"
		}
		w("**Local services** (`%s`, %s): %s", c.Rel, strings.Join(c.DBServices, ", "), state)
		w("")
		w("```bash")
		w("docker compose -f %s up -d %s", c.Rel, strings.Join(c.DBServices, " "))
		w("```")
		w("")
	}
	for _, pkg := range p.Pkgs {
		title := pkg.Name
		if pkg.Rel != "." {
			title += " (`" + pkg.Rel + "`)"
		}
		w("### %s", title)
		w("")
		stack := pkg.PM
		if pkg.Framework != "" {
			stack = pkg.Framework + ", " + pkg.PM
		}
		w("Stack: %s", stack)
		if port := project.PortFor(pkg); port != "" {
			w("")
			w("Expected port: %s", port)
		}
		w("")
		w("```bash")
		if pkg.Rel != "." {
			w("cd %s", pkg.Rel)
		}
		if s := project.DevScript(pkg); s != "" {
			w("%s run %s", pkg.PM, s)
		} else {
			w("# no dev/start script found in package.json, check the README")
		}
		w("```")
		w("")
		var others []string
		for _, s := range []string{"build", "test", "lint", "migrate", "seed"} {
			if c, ok := pkg.Scripts[s]; ok {
				others = append(others, fmt.Sprintf("- `%s run %s`: `%s`", pkg.PM, s, c))
			}
		}
		if len(others) > 0 {
			w("Other scripts:")
			w("")
			for _, o := range others {
				w("%s", o)
			}
			w("")
		}
	}

	for _, m := range p.GoModules {
		title := m.Module
		if m.Rel != "." {
			title += " (`" + m.Rel + "`)"
		}
		w("### %s", title)
		w("")
		stack := "Go"
		if m.GoWanted != "" {
			stack += " " + m.GoWanted
		}
		w("Stack: %s", stack)
		w("")
		w("```bash")
		if m.Rel != "." {
			w("cd %s", m.Rel)
		}
		w("go mod download                 # dependencies")
		w("%s", strings.Join(golang.BuildArgs(m), " "))
		w("go test ./...                   # tests")
		w("```")
		w("")
	}

	// Config changes
	w("## What you may need to change")
	w("")
	any := false
	for _, pkg := range p.Pkgs {
		if guideEnv(&b, pkg) {
			any = true
		}
	}
	if !any {
		w("No env files or environment variables were detected. The project should run on its defaults.")
		w("")
	}

	services.GuideServices(&b, p)
	repos.GuideCompanions(&b, p)

	// Databases
	var dbLines []string
	for _, pkg := range p.Pkgs {
		if len(pkg.DBHints) > 0 {
			dbLines = append(dbLines, fmt.Sprintf("- `%s` uses: %s", pkg.Rel, strings.Join(pkg.DBHints, ", ")))
		}
	}
	if len(dbLines) > 0 {
		w("## Databases")
		w("")
		for _, l := range dbLines {
			w("%s", l)
		}
		w("")
		w("Make sure the database is reachable with the connection settings in your `.env` before starting the app.")
		for _, pkg := range p.Pkgs {
			if pkg.Prisma {
				w("")
				w("Prisma detected in `%s`: run `npx prisma generate`, then `npx prisma migrate dev` once the database is up.", pkg.Rel)
			}
		}
		w("")
	}

	if len(p.OtherStacks) > 0 {
		w("## Not handled by gclone yet")
		w("")
		for _, s := range p.OtherStacks {
			w("- %s", s)
		}
		w("")
		w("These parts were cloned but not set up. Check the repository README for their steps.")
		w("")
	}

	if p.Verify != nil {
		b.WriteString(verify.VerifySection(p.Verify))
	}

	w("---")
	w("Keep `.env` files out of version control. This guide is excluded from `git status` through `.git/info/exclude`.")

	path := filepath.Join(p.Dir, project.GuideName)
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return "", err
	}
	excludeFromGit(p.Dir, project.GuideName)
	return path, nil
}

// guideEnv writes the env section for one package and reports whether it wrote anything.
func guideEnv(b *strings.Builder, pkg *project.Pkg) bool {
	if len(pkg.EnvVars) == 0 && len(pkg.MissingVars) == 0 {
		return false
	}
	w := func(format string, a ...interface{}) { fmt.Fprintf(b, format+"\n", a...) }

	w("### Environment: %s", verify.UnitLabel(pkg.Rel))
	w("")
	switch {
	case pkg.EnvCreated:
		w("`.env` was created from `%s` with its default values.", pkg.EnvExample)
	case pkg.EnvExample != "":
		w("`.env` already existed, so it was left untouched. Compare it with `%s`.", pkg.EnvExample)
	default:
		w("No example env file was found. These variables come from the source code.")
	}
	w("")

	var blocking, review, ok []project.EnvVar
	for _, v := range pkg.EnvVars {
		switch v.Kind {
		case "blocking":
			blocking = append(blocking, v)
		case "review":
			review = append(review, v)
		default:
			ok = append(ok, v)
		}
	}
	if len(blocking) > 0 {
		w("**Set these first** (empty or placeholder, the app will likely fail without them):")
		w("")
		for _, v := range blocking {
			w("- `%s`: %s", v.Key, describe(v))
		}
		w("")
	}
	if len(review) > 0 {
		w("**Works on defaults, change for real use:**")
		w("")
		for _, v := range review {
			// Values are deliberately not printed: example files sometimes hold real secrets.
			w("- `%s`: %s", v.Key, describe(v))
		}
		w("")
	}
	if len(ok) > 0 {
		keys := make([]string, 0, len(ok))
		for _, v := range ok {
			keys = append(keys, "`"+v.Key+"`")
		}
		sort.Strings(keys)
		w("**Defaults that should be fine:** %s", strings.Join(keys, ", "))
		w("")
	}
	if len(pkg.MissingVars) > 0 {
		keys := make([]string, 0, len(pkg.MissingVars))
		for _, k := range pkg.MissingVars {
			keys = append(keys, "`"+k+"`")
		}
		w("**Read by the code but not in the example file** (check the README for what they should be): %s", strings.Join(keys, ", "))
		w("")
	}
	return true
}

func describe(v project.EnvVar) string {
	if v.Comment != "" {
		return v.Reason + ". Note from the example file: " + v.Comment
	}
	return v.Reason
}

// excludeFromGit keeps the generated guide out of `git status`.
func excludeFromGit(dir, name string) {
	info := filepath.Join(dir, ".git", "info")
	if err := os.MkdirAll(info, 0o755); err != nil {
		return
	}
	path := filepath.Join(info, "exclude")
	b, _ := os.ReadFile(path)
	if strings.Contains(string(b), name) {
		return
	}
	f, err := os.OpenFile(path, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
	if err != nil {
		return
	}
	defer f.Close()
	if len(b) > 0 && !strings.HasSuffix(string(b), "\n") {
		_, _ = f.WriteString("\n")
	}
	_, _ = f.WriteString(name + "\n")
}
